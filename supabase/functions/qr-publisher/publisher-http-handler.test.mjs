import {makePublisherHttpHandler} from "./publisher-http-handler.mjs";
import assert from "node:assert/strict";
const token="a".repeat(64),headers={"content-type":"application/json","x-nohut-agent-token":token};
let calls=0;
const dispatch=async x=>{calls++;assert.equal(x.token,token);return {status:200,body:{status:"no_change"}}};
const req=(body="{}",h=headers)=>new Request("https://example.invalid/qr-publisher",{method:"POST",headers:h,body});
const disabled=makePublisherHttpHandler({dispatch});
assert.equal((await disabled(req())).status,503);
const handle=makePublisherHttpHandler({dispatch,enabled:()=>true,maxBytes:128});
assert.equal((await handle(new Request("https://example.invalid/qr-publisher"))).status,405);
assert.equal((await handle(req("{}",{"content-type":"application/json"}))).status,401);
assert.equal((await handle(req("{}",{...headers,"content-type":"text/plain"}))).status,415);
assert.equal((await handle(req("{}",{...headers,"content-encoding":"gzip"}))).status,415);
assert.equal((await handle(req("{}",{...headers,"content-length":"129"}))).status,413);
assert.equal((await handle(req(" ".repeat(129)))).status,413);
assert.equal((await handle(req("{"))).status,400);
assert.equal((await handle(req(new Uint8Array([255])))).status,400);
assert.equal(calls,0);
const ok=await handle(req(JSON.stringify({name:"اختبار"})));
assert.equal(ok.status,200);assert.equal(ok.headers.get("cache-control"),"no-store");assert.equal(calls,1);
const fail=makePublisherHttpHandler({enabled:()=>true,dispatch:async()=>{throw Error("secret upstream error")}});
const err=await fail(req());assert.equal(err.status,503);assert.deepEqual(await err.json(),{error:"publisher_unavailable"});
console.log("11 HTTP boundary checks passed");
