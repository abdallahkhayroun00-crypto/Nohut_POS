\set ON_ERROR_STOP on
begin;
do $$
declare r uuid:=gen_random_uuid(); e uuid:=gen_random_uuid(); u uuid:=gen_random_uuid(); d uuid:=gen_random_uuid(); s uuid:=gen_random_uuid();
  phone uuid:=gen_random_uuid(); ps uuid:=gen_random_uuid(); req uuid:=gen_random_uuid(); second uuid:=gen_random_uuid();
  first_info jsonb; again jsonb; token text:=repeat('1',64); token2 text:=repeat('2',64); old_agent uuid;
begin
  insert into nohut_private.restaurants(restaurant_id) values(r);
  insert into nohut_private.authority_epochs(restaurant_id,authority_epoch) values(r,e);
  insert into nohut_private.sync_checkpoints(restaurant_id,authority_epoch) values(r,e);
  insert into nohut_private.app_users(user_id,restaurant_id,username,role_template,is_owner) values(u,r,'synthetic-agent-setup','Yönetici',true);
  perform nohut_private.enroll_device(u,phone,ps,'yonetici','Synthetic phone');
  perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'session_id',s,'aal','aal2')::text,true);
  set local role service_role;
  perform set_config('nohut.synthetic_ticket',public.nohut_issue_windows_bootstrap(r),true);
  reset role;
  set local role authenticated;
  perform public.nohut_register_windows_device(d,'Synthetic Windows',current_setting('nohut.synthetic_ticket'));
  first_info:=public.nohut_enroll_agent(d,1,e,req,encode(sha256(convert_to(token,'UTF8')),'hex'));
  again:=public.nohut_enroll_agent(d,1,e,req,encode(sha256(convert_to(token,'UTF8')),'hex'));
  if first_info is distinct from again or first_info->>'status'<>'enrolled' or first_info ? 'token' then raise exception 'enrollment ACK not recoverable'; end if;
  begin perform public.nohut_enroll_agent(d,1,e,req,encode(sha256(convert_to(token2,'UTF8')),'hex'));
    raise exception 'enrollment request body changed'; exception when invalid_parameter_value then null; end;
  begin perform public.nohut_enroll_agent(d,1,gen_random_uuid(),second,encode(sha256(convert_to(token2,'UTF8')),'hex'));
    raise exception 'foreign epoch enrolled'; exception when insufficient_privilege then null; end;
  begin perform public.nohut_enroll_agent(d,2,e,second,encode(sha256(convert_to(token2,'UTF8')),'hex'));
    raise exception 'stale permissions enrolled'; exception when insufficient_privilege then null; end;
  reset role;
  if (nohut_private.authenticate_windows_agent(token)).agent_id::text<>first_info->>'agent_id' then raise exception 'client credential not installed'; end if;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'session_id',s,'aal','aal1')::text,true);
  set local role authenticated;
  begin perform public.nohut_enroll_agent(d,1,e,second,encode(sha256(convert_to(token2,'UTF8')),'hex'));
    raise exception 'MFA downgrade enrolled'; exception when insufficient_privilege then null; end;
  reset role;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'session_id',ps,'aal','aal2')::text,true);
  set local role authenticated;
  begin perform public.nohut_enroll_agent(phone,1,e,second,encode(sha256(convert_to(token2,'UTF8')),'hex'));
    raise exception 'phone enrolled agent'; exception when insufficient_privilege then null; end;
  begin perform public.nohut_revoke_agent(phone,1,(first_info->>'agent_id')::uuid);
    raise exception 'phone revoked agent'; exception when insufficient_privilege then null; end;
  reset role;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'session_id',s,'aal','aal2')::text,true);
  update nohut_private.sessions set revoked_at=clock_timestamp() where session_id=s;
  set local role authenticated;
  begin perform public.nohut_enroll_agent(d,1,e,second,encode(sha256(convert_to(token2,'UTF8')),'hex'));
    raise exception 'revoked session enrolled'; exception when insufficient_privilege then null; end;
  reset role;
  update nohut_private.sessions set revoked_at=null where session_id=s;
  update nohut_private.devices set revoked_at=clock_timestamp() where device_id=d;
  set local role authenticated;
  begin perform public.nohut_revoke_agent(d,1,(first_info->>'agent_id')::uuid);
    raise exception 'revoked device revoked agent'; exception when insufficient_privilege then null; end;
  reset role;
  update nohut_private.devices set revoked_at=null where device_id=d;
  set local role authenticated;
  again:=public.nohut_enroll_agent(d,1,e,second,encode(sha256(convert_to(token2,'UTF8')),'hex'));
  reset role;
  old_agent:=(first_info->>'agent_id')::uuid;
  if again->>'agent_id'=first_info->>'agent_id' then raise exception 'rotation not new identity'; end if;
  begin perform nohut_private.authenticate_windows_agent(token); raise exception 'old credential still active'; exception when insufficient_privilege then null; end;
  perform nohut_private.authenticate_windows_agent(token2);
  set local role authenticated;
  if public.nohut_enroll_agent(d,1,e,req,encode(sha256(convert_to(token,'UTF8')),'hex'))->>'status'<>'revoked' then raise exception 'old request rotated again'; end if;
  begin perform public.nohut_revoke_agent(d,1,gen_random_uuid()); raise exception 'unknown agent revoked'; exception when insufficient_privilege then null; end;
  perform public.nohut_revoke_agent(d,1,(again->>'agent_id')::uuid);
  perform public.nohut_revoke_agent(d,1,(again->>'agent_id')::uuid);
  reset role;
  begin perform nohut_private.authenticate_windows_agent(token2); raise exception 'revoked credential active'; exception when insufficient_privilege then null; end;
  if (select count(*) from nohut_private.agent_enrollment_requests where restaurant_id=r)<>2 then raise exception 'duplicate enrollment receipts'; end if;
  set local role anon;
  begin perform public.nohut_enroll_agent(d,1,e,req,repeat('a',64)); raise exception 'anon enrolled'; exception when insufficient_privilege then null; end;
  reset role;
end $$;
rollback;
